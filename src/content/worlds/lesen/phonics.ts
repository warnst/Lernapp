/** Liefert einen klaren deutschen Vorlesetext für eine einzelne Silbe. */
export function speakSyllable(syllable: string): string {
  const key = syllable.trim().toLowerCase();
  return SYLLABLE_OVERRIDES[key] ?? syllable;
}

/**
 * Erzeugt die sanfte Lautsynthese-Erklärung für die Silbenrutsche:
 * z. B. M + A → „Mmmm … Aaaa … zusammen klingt es: Maa!“
 */
export function speakBlend(consonant: string, vowel: string): string {
  const cInfo = LETTERS[consonant] ?? LETTERS[consonant.toUpperCase()];
  const vInfo = LETTERS[vowel] ?? LETTERS[vowel.toUpperCase()];
  const combined = `${consonant}${vowel.toLowerCase()}`;
  const result = speakSyllable(combined);
  if (cInfo?.kind === 'continuant' && vInfo) {
    return `${cInfo.soundCue} … ${vInfo.soundCue} … zusammen klingt es: ${result}!`;
  }
  if (cInfo && vInfo) {
    return `${cInfo.soundCue} und ${vInfo.soundCue} zusammen klingen: ${result}!`;
  }
  return `${result}!`;
}
